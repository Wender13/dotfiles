#!/bin/bash
# MENU_DESC: Login screen (GDM): dark, icons, no logo
# CATEGORY: LOGIN SCREEN
set -euo pipefail

SCRIPT_DIR="$(dirname "$(realpath "$0")")"
source "$SCRIPT_DIR/lib.sh"
detect_distro

# A minimal login screen that matches the desktop: dark style, your icon and cursor themes,
# clock, touchpad and keyboard from style/gnome/dconf/desktop.ini, and no distribution logo.
# Only GDM's own dconf database is used (the supported way, kept across updates); the
# background and the shell theme would need a rebuilt gnome-shell theme resource, which
# every gnome-shell update undoes, so they are left alone.
GNOME_DIR="$DOTFILES_DIR/style/gnome"

require_gnome

print_header "Configuring the login screen (GDM)"

# Fedora reads /etc/dconf/db/gdm.d (system-db:gdm, compiled by 'dconf update'). Debian and
# Ubuntu compile the greeter defaults from /usr/share/gdm/dconf with generate-config.
GDM_PROFILE=""
for profile in /etc/dconf/profile/gdm /usr/share/dconf/profile/gdm; do
    if [ -f "$profile" ]; then
        GDM_PROFILE="$profile"
        break
    fi
done
if [ -z "$GDM_PROFILE" ]; then
    echo -e "${C_YELLOW}GDM not found (another display manager?). Skipping the login screen.${C_RESET}"
    exit 0
fi
if grep -qx 'system-db:gdm' "$GDM_PROFILE"; then
    GDM_SETTINGS="/etc/dconf/db/gdm.d/95-dotfiles"
elif [ -x /usr/share/gdm/generate-config ]; then
    GDM_SETTINGS="/usr/share/gdm/dconf/95-dotfiles"
else
    echo -e "${C_RED}Unknown GDM dconf layout in $GDM_PROFILE. Nothing was changed.${C_RESET}" >&2
    exit 1
fi

ensure_command dconf dconf-cli dconf

# desktop.ini keys the login screen shares with the desktop, matched against "section/key"
LOGIN_KEYS='org/gnome/desktop/interface/(color-scheme|accent-color|icon-theme|cursor-theme|cursor-size|clock-format|clock-show-seconds|clock-show-weekday|show-battery-percentage)'
LOGIN_KEYS+='|org/gnome/desktop/peripherals/touchpad/.*'
LOGIN_KEYS+='|org/gnome/desktop/input-sources/(sources|xkb-options)'

login_settings() {
    local section="" printed="" line
    echo "# Login screen settings, generated by 14-loginScreen.sh from style/gnome/dconf/desktop.ini"
    while IFS= read -r line; do
        if [[ "$line" =~ ^\[(.*)\]$ ]]; then
            section="${BASH_REMATCH[1]}"
            continue
        fi
        if [[ "$line" != *=* ]] || ! [[ "$section/${line%%=*}" =~ ^($LOGIN_KEYS)$ ]]; then
            continue
        fi
        if [ "$printed" != "$section" ]; then
            printf '\n[%s]\n' "$section"
            printed="$section"
        fi
        echo "$line"
    done < "$GNOME_DIR/dconf/desktop.ini"
    # No logo under the user list (Fedora sets its own in a schema override)
    printf '\n[org/gnome/login-screen]\nlogo=%s\n' "''"
}

settings="$(mktemp)"
trap 'rm -f "$settings"' EXIT
login_settings > "$settings"

# ─── Settings ─────────────────────────────────────────────────────────────────
if [ -f "$GDM_SETTINGS" ] && cmp -s "$settings" "$GDM_SETTINGS"; then
    echo -e "${C_YELLOW}Login screen settings already applied.${C_RESET}"
elif only_missing && [ ! -f "$GDM_SETTINGS" ]; then
    # The login screen always has a look; in this mode it stays as it is
    keep_existing "the current login screen look"
    exit 0
elif only_missing; then
    keep_existing "your login screen settings ($GDM_SETTINGS)"
else
    sudo install -D -m 0644 "$settings" "$GDM_SETTINGS"
    if [ "$GDM_SETTINGS" = "/etc/dconf/db/gdm.d/95-dotfiles" ]; then
        sudo dconf update
    else
        sudo /usr/share/gdm/generate-config
    fi
    echo "Wrote $GDM_SETTINGS"
fi

# ─── Icon and cursor themes ───────────────────────────────────────────────────
# Module 10 installs them in your home, which the login screen cannot read, and mutter only
# looks for cursors in /usr/share/icons (not /usr/local). So the login screen gets a copy.
print_header "Login screen icon and cursor themes"

SYSTEM_ICONS="/usr/share/icons"
ICON_DIRS=("$HOME/.local/share/icons" "$HOME/.icons")

# Value of a key in the generated settings (strings only), or nothing
setting() {
    sed -n "s/^$1='\(.*\)'$/\1/p" "$settings"
}

# A theme folder and the sibling themes its symlinks point to (Tela-circle-dark links into
# Tela-circle), one name per line
theme_and_dependencies() {
    local root name=$2 links dep
    root="$(realpath "$1")"
    echo "$name"
    links="$(find "$root/$name" -type l -exec realpath -m {} +)"
    sed -n "s|^$root/\([^/]*\)/.*|\1|p" <<< "$links" | sort -u | while read -r dep; do
        if [ "$dep" != "$name" ]; then
            echo "$dep"
        fi
    done
}

owned_by_package() {
    if is_dnf; then
        rpm -qf "$1" &> /dev/null
    else
        dpkg -S "$1" &> /dev/null
    fi
}

copy_theme() {
    sudo rm -rf -- "${SYSTEM_ICONS:?}/$1"
    sudo install -d -m 0755 "$SYSTEM_ICONS"
    sudo cp -R --preserve=mode,timestamps "$2/$1" "$SYSTEM_ICONS/$1"
    echo "Copied $1 to $SYSTEM_ICONS"
}

missing=()
outdated=()
declare -A source_root=()
for theme in "$(setting icon-theme)" "$(setting cursor-theme)"; do
    if [ -z "$theme" ]; then
        continue
    fi
    # Theme names become paths under /usr/share/icons: nothing that could leave it
    if ! [[ "$theme" =~ ^[A-Za-z0-9._+-]+$ ]] || [[ "$theme" == .* ]]; then
        echo -e "${C_RED}Invalid theme name: '$theme'${C_RESET}" >&2
        exit 1
    fi
    root=""
    for dir in "${ICON_DIRS[@]}"; do
        if [ -d "$dir/$theme" ]; then
            root="$dir"
            break
        fi
    done
    if [ -z "$root" ]; then
        if [ -d "$SYSTEM_ICONS/$theme" ]; then
            echo -e "${C_YELLOW}$theme is installed for the whole system.${C_RESET}"
        else
            echo -e "${C_YELLOW}$theme is not installed: run 10-themesAndGrub.sh first. The login screen uses the default until then.${C_RESET}"
        fi
        continue
    fi
    names="$(theme_and_dependencies "$root" "$theme")"
    while read -r name; do
        if [ -n "${source_root[$name]:-}" ]; then
            continue
        fi
        source_root[$name]="$root"
        if [ ! -d "$SYSTEM_ICONS/$name" ]; then
            missing+=("$name")
        elif owned_by_package "$SYSTEM_ICONS/$name"; then
            echo -e "${C_YELLOW}$name in $SYSTEM_ICONS comes from a system package; left as it is.${C_RESET}"
        elif ! diff -rq --no-dereference "$root/$name" "$SYSTEM_ICONS/$name" &> /dev/null; then
            outdated+=("$name")
        else
            echo -e "${C_YELLOW}$name is up to date for the login screen.${C_RESET}"
        fi
    done <<< "$names"
done

for name in "${missing[@]}"; do
    copy_theme "$name" "${source_root[$name]}"
done

# The copy differs from the version in your home (updated by module 10): update policy
lines=()
for name in "${outdated[@]}"; do
    lines+=("$name copia da tela de login -> versao do seu HOME")
done
if confirm_updates "Temas da tela de login" "${lines[@]}"; then
    for name in "${outdated[@]}"; do
        copy_theme "$name" "${source_root[$name]}"
    done
fi

echo -e "${C_GREEN}Login screen configured. It shows up the next time the login screen opens (log out or restart).${C_RESET}"
