#!/bin/bash
# Captures the current GNOME configuration into the repository (style/gnome/):
#   dconf/*.ini               settings applied by scripts/11-gnomeSettings.sh
#   extensions.txt            enabled extensions (UUID and Fedora package, when one exists)
#   burn-my-windows/profiles  effect profiles referenced by the extension settings
#
# What is kept out of the repository:
#   - sections outside the allowlists below (accounts, network credentials, recent folders...)
#   - machine state keys (DROP_KEYS: timestamps, window sizes, wallpaper paths)
#   - any key whose name or value looks like a secret or an e-mail (SECRET_KEY_RE,
#     SECRET_VALUE_RE, EMAIL_RE); dropped keys are listed at the end of the run
#   - the home path, replaced by the @HOME@ placeholder
# The run aborts if a secret-looking value or the home path still reaches the output.
# Heuristics are not a guarantee: always review 'git diff' before committing.
#
# Usage (inside the GNOME session, as your normal user):
#   bash style/gnome/bin/export-gnome-settings.sh
set -euo pipefail

GNOME_DIR="$(realpath "$(dirname "$(realpath "$0")")/..")"
DCONF_DIR="$GNOME_DIR/dconf"
mkdir -p "$DCONF_DIR"

DUMP="$(mktemp)"
DROPPED="$(mktemp)"
trap 'rm -f "$DUMP" "$DROPPED"' EXIT
dconf dump / > "$DUMP"

# Keys that hold machine state or personal paths, matched against "section/key"
DROP_KEYS='.*/picture-uri(-dark)?'
DROP_KEYS+='|org/gnome/shell/(app-picker-layout|last-selected-power-profile|welcome-dialog-last-shown-version|command-history|had-bluetooth-devices-setup)'
DROP_KEYS+='|org/gnome/shell/extensions/blur-my-shell/rounded-blur-found'
DROP_KEYS+='|org/gnome/shell/extensions/burn-my-windows/(last-extension-version|prefs-open-count|preview-effect)'
DROP_KEYS+='|org/gnome/shell/extensions/caffeine/(user-enabled|indicator-position-max|cli-toggle|toggle-state)'
DROP_KEYS+='|org/gnome/Ptyxis/window-size'
DROP_KEYS+='|org/gnome/desktop/peripherals/keyboard/numlock-state'
DROP_KEYS+='|org/gnome/nautilus/preferences/migrated-gtk-settings'

# Secret detection (case-insensitive). Extensions, custom shortcuts and terminal
# profiles may store tokens or commands with credentials, so every exported key is checked.
SECRET_KEY_RE='token|secret|passw|api[-_]?key|app[-_]?id|credential|oauth|auth[-_]?key|private[-_]?key|cookie'
SECRET_VALUE_RE='gh[pousr]_[a-z0-9]|github_pat_|glpat-|xox[abprs]-|eyj[a-z0-9_-]+[.]eyj|-----begin|bearer |authorization:|(password|passwd|token|secret|api[-_]?key)='
# Extension UUIDs look like e-mails, so the extension lists are not checked for e-mails
EMAIL_RE='[a-z0-9._%+-]+@[a-z0-9-]+([.][a-z0-9-]+)*[.][a-z][a-z]+'
EMAIL_EXEMPT_KEYS='org/gnome/shell/(enabled|disabled)-extensions'

# $1: output file name, $2: sections to keep (ERE, whole section path)
export_group() {
    local out="$DCONF_DIR/$1" sections=$2
    {
        echo "# Generated by style/gnome/bin/export-gnome-settings.sh. Applied with: dconf load /"
        echo "# @HOME@ is replaced by the home directory of the user applying it."
        awk -v sec_re="^($sections)\$" -v drop_re="^($DROP_KEYS)\$" -v home="$HOME" \
            -v secret_key_re="$SECRET_KEY_RE" -v secret_value_re="$SECRET_VALUE_RE" \
            -v email_re="$EMAIL_RE" -v email_exempt_re="^($EMAIL_EXEMPT_KEYS)\$" -v report="$DROPPED" '
            function replace_all(s, find, repl,    out, i) {
                out = ""
                while ((i = index(s, find)) > 0) {
                    out = out substr(s, 1, i - 1) repl
                    s = substr(s, i + length(find))
                }
                return out s
            }
            function flush() { if (keep && buf != "") printf "\n[%s]\n%s", section, buf }
            /^\[.*\]$/ { flush(); section = substr($0, 2, length($0) - 2); keep = (section ~ sec_re); buf = ""; next }
            keep && index($0, "=") > 0 {
                key = substr($0, 1, index($0, "=") - 1)
                value = tolower(substr($0, index($0, "=") + 1))
                path = section "/" key
                if (path ~ drop_re) next
                # Only text values can hold a secret: booleans and numbers have no quotes
                if (tolower(key) ~ secret_key_re && value ~ /[\047"]/) { print path "  (secret-like key name)" >> report; next }
                if (value ~ secret_value_re)        { print path "  (secret-like value)" >> report; next }
                if (path !~ email_exempt_re && value ~ email_re) { print path "  (e-mail address)" >> report; next }
                buf = buf replace_all($0, home, "@HOME@") "\n"
            }
            END { flush() }
        ' "$DUMP"
    } > "$out"
    echo "Wrote $out"
}

export_group keybindings.ini \
    'org/gnome/desktop/wm/keybindings|org/gnome/shell/keybindings|org/gnome/mutter/keybindings|org/gnome/mutter/wayland/keybindings|org/gnome/settings-daemon/plugins/media-keys(/custom-keybindings/[^/]+)?'

export_group desktop.ini \
    'org/gnome/desktop/(interface|input-sources|peripherals/[^/]+|session|wm/preferences|a11y/[^/]+|break-reminders/[^/]+|screen-time-limits|privacy|sound|search-providers|datetime|calendar)|org/gnome/mutter|org/gnome/settings-daemon/plugins/(color|power)|org/gnome/system/location'

export_group shell.ini \
    'org/gnome/shell|org/gnome/shell/extensions/.+'

export_group apps.ini \
    'org/gnome/Ptyxis(/Shortcuts|/Profiles/[^/]+)?|org/gnome/nautilus/(preferences|list-view|icon-view)|org/gnome/TextEditor'

# ─── Enabled extensions ───────────────────────────────────────────────────────
# Fedora package of an extension, or nothing when it is not packaged
extension_package() {
    # An empty result just means "not packaged"; '|| true' keeps that from aborting the export.
    if [ -d "/usr/share/gnome-shell/extensions/$1" ]; then
        rpm -qf --qf '%{NAME}' "/usr/share/gnome-shell/extensions/$1" 2>/dev/null || true
    elif command -v dnf5 &>/dev/null; then
        dnf repoquery --available --qf '%{name}\n' \
            --whatprovides "/usr/share/gnome-shell/extensions/$1/metadata.json" 2>/dev/null | head -n1 || true
    fi
}

# $1: "" for an enabled extension or "disabled ", $2: UUID
extension_line() {
    local package
    package="$(extension_package "$2")"
    if [ -n "$package" ]; then
        printf '%-55s %s\n' "$1$2" "$package"
    else
        printf '%s\n' "$1$2"
    fi
}

# A disabled extension is kept in the list when you installed it: it is in your extensions
# folder, or its Fedora package was installed by you (dnf reason "User"). Extensions that
# come with the system (GNOME Classic, the Fedora logo) are left out.
user_installed_extension() {
    local package reason
    [ -d "$HOME/.local/share/gnome-shell/extensions/$1" ] && return 0
    [ -d "/usr/share/gnome-shell/extensions/$1" ] || return 1
    package="$(extension_package "$1")"
    [ -n "$package" ] || return 1
    reason="$(dnf repoquery --installed --qf '%{reason}' "$package" 2>/dev/null || true)"
    [ "$reason" = "User" ]
}

{
    echo "# GNOME extensions to install: UUID and, when Fedora packages it, the package name."
    echo "# Generated by style/gnome/bin/export-gnome-settings.sh (can also be edited by hand)."
    echo "# Packaged ones are installed with dnf on Fedora; the rest come from extensions.gnome.org."
    echo "# \"disabled\" ones are installed but stay off (org/gnome/shell in dconf/shell.ini decides"
    echo "# what is enabled); their settings are exported as well."
    gnome-extensions list --enabled | while read -r uuid; do
        extension_line "" "$uuid"
    done
    gnome-extensions list --disabled | while read -r uuid; do
        if user_installed_extension "$uuid"; then
            extension_line "disabled " "$uuid"
        fi
    done
} > "$GNOME_DIR/extensions.txt"
echo "Wrote $GNOME_DIR/extensions.txt"

# ─── Extension data files ─────────────────────────────────────────────────────
BMW_SRC="$HOME/.config/burn-my-windows/profiles"
BMW_DEST="$GNOME_DIR/burn-my-windows/profiles"
if compgen -G "$BMW_SRC/*.conf" > /dev/null; then
    if grep -Eiq "$SECRET_VALUE_RE" "$BMW_SRC"/*.conf; then
        echo "ERROR: a Burn My Windows profile looks like it contains a secret. Not copied." >&2
        exit 1
    fi
    mkdir -p "$BMW_DEST"
    rm -f "$BMW_DEST"/*.conf
    cp "$BMW_SRC"/*.conf "$BMW_DEST/"
    echo "Copied Burn My Windows profiles to $BMW_DEST"
fi

# ─── Safety gates ─────────────────────────────────────────────────────────────
if [ -s "$DROPPED" ]; then
    echo "Not exported (possible secrets or personal data; configure these by hand):" >&2
    sed 's/^/  - /' "$DROPPED" >&2
fi

# Second, independent pass over the written values (not key names, which may legitimately
# contain words like "password", e.g. remember-mount-password=true)
if awk -v re="$SECRET_VALUE_RE" '
        /^#/ || index($0, "=") == 0 { next }
        tolower(substr($0, index($0, "=") + 1)) ~ re { found = 1 }
        END { exit !found }
    ' "$DCONF_DIR"/*.ini; then
    echo "ERROR: a secret-looking value reached $DCONF_DIR. Review and remove it before committing." >&2
    exit 1
fi
if grep -rqF "$HOME" "$DCONF_DIR"; then
    echo "ERROR: the home path is still present in $DCONF_DIR. Review before committing." >&2
    exit 1
fi
echo "Done. Review the changes with 'git diff' before committing."
